//! Tor client keys the daemon generates for peers, and what a granted peer needs to use
//! one (ADR 0045).

use super::mutations::Catalog;
use super::*;
use crate::api::DaemonEvent;
use crate::networks::tor_client_key;
use crate::state::NewActivity;
use crate::AppState;
use socketguard_core::api_types::{ShareResponse, TorKeyResponse, TorShare};
use socketguard_core::{
    grants_for_app, new_id, ActivityKind, Credential, CredentialKind, Locator, NetworkKind, Subject,
};

impl Engine {
    /// Generate an x25519 key pair for `peer_id`: the public half becomes the peer's
    /// `tor_client_key` credential, the private half is stored (like the onion service
    /// keys) so `share` can hand it out. Replaces the key generated before; a key the user
    /// pasted stays. The private key is returned here, once more than `share` would.
    pub async fn generate_tor_key(
        &self,
        state: &AppState,
        peer_id: &str,
    ) -> Result<TorKeyResponse, EngineError> {
        let peer = self.get_peer(state, peer_id).await?;
        let key = tor_client_key::generate();
        let credential = Credential {
            id: new_id(),
            kind: CredentialKind::TorClientKey,
            value: key.public.clone(),
            label: Some("generated by SocketGuard".to_string()),
        };
        state
            .db
            .replace_generated_tor_key(peer_id, &credential, &key.private)
            .await
            .map_err(|e| Self::conflict_or_internal(e, "this Tor client key"))?;
        let applied = self.apply_firewall(state).await;
        let activity = NewActivity::new(
            ActivityKind::PeerChanged,
            format!("Generated a Tor client key for peer {}", peer.label),
        )
        .peer(peer_id);
        self.commit(
            state,
            applied,
            Some(activity),
            &[DaemonEvent::PeersChanged, DaemonEvent::GrantsChanged],
        )
        .await?;
        Ok(TorKeyResponse {
            credential,
            private_key: key.private,
        })
    }

    /// For each onion service of the app, the client authorization line of every peer that
    /// is granted access and has a key the daemon generated.
    pub async fn share(
        &self,
        state: &AppState,
        app_id: &str,
    ) -> Result<ShareResponse, EngineError> {
        let cat = Catalog::load(state).await?;
        let app = cat
            .app(app_id)
            .ok_or_else(|| EngineError::NotFound(format!("app {app_id}")))?;
        let keys = state.db.tor_client_keys().await?;
        let networks = self.networks();
        let grants = grants_for_app(&cat.grants, &cat.tags, app_id);
        let mut tor: Vec<TorShare> = Vec::new();
        for address in &app.addresses {
            let Locator::Onion { hostname } = &address.locator else {
                continue;
            };
            if !networks
                .iter()
                .any(|n| n.id == address.network_id && n.kind == NetworkKind::Tor)
            {
                continue;
            }
            for grant in grants.iter().filter(|g| {
                g.network_id
                    .as_deref()
                    .is_none_or(|n| n == address.network_id)
            }) {
                let peers: Vec<&socketguard_core::Peer> = match &grant.subject {
                    Subject::Anyone => vec![],
                    Subject::Peer(id) => cat.peer(id).into_iter().collect(),
                    Subject::Group(id) => cat
                        .group(id)
                        .map(|g| g.members.iter().filter_map(|m| cat.peer(m)).collect())
                        .unwrap_or_default(),
                };
                for peer in peers {
                    for cred in &peer.credentials {
                        let Some(private) = keys.get(&cred.id) else {
                            continue;
                        };
                        let already = tor
                            .iter()
                            .any(|t| t.hostname == *hostname && t.peer_id == peer.id);
                        if !already {
                            tor.push(TorShare {
                                network_id: address.network_id.clone(),
                                hostname: hostname.clone(),
                                peer_id: peer.id.clone(),
                                peer_label: peer.label.clone(),
                                auth_private: tor_client_key::auth_private_line(hostname, private),
                            });
                        }
                    }
                }
            }
        }
        tor.sort_by(|a, b| (&a.hostname, &a.peer_label).cmp(&(&b.hostname, &b.peer_label)));
        Ok(ShareResponse { tor })
    }
}
